def _seed_price_pages():
  now = datetime.now(timezone.utc)
  created = []
  for code in PRICE_CODES:
    meta = PRICE_META[code]
    slug = "prices-{}".format(code)
    page = app_tables.cms_pages.get(slug=slug)
    if page is not None:
      continue
    page = app_tables.cms_pages.add_row(
      slug=slug,
      title=meta["title"],
      status="published",
      settings={
        "publish_date": now.strftime("%d.%m.%Y"),
        "excerpt": meta["seo_description"],
        "seo_title": meta["seo_title"],
        "seo_description": meta["seo_description"],
        "keywords": "цены, монтаж, кондиционеры, VRV, VRF, вентиляция, ЭКО-КЛИМАТ",
        "social_image_url": meta["image"],
        "price_source": {
          "conditioners": SOURCE_CONDITIONING,
          "vrf": SOURCE_VRF,
          "ventilation": SOURCE_VENTILATION,
        }[code],
        "price_category": "prices",
        "price_code": code,
      },
      updated_at=now
    )
    app_tables.cms_modules.add_row(
      page=page, code="html", position=10,
      content={"title": meta["title"], "html": PAGE_HTML[code]()},
      enabled=True
    )
    created.append(slug)
  if created:
    Core.log_audit(
      action="cms.price_pages_seeded",
      entity_type="cms_page",
      details={"slugs": created},
      created_at=now
    )


@anvil.server.callable
def get_price_page(code):
  if not isinstance(code, str):
    code = "ventilation"
  code = code.strip().lower()
  if code not in PRICE_CODES:
    return {"ok": False, "message": "Страница цен не найдена."}
  _seed_price_pages()

  slug = "prices-{}".format(code)
  page = app_tables.cms_pages.get(slug=slug, status="published")
  if page is not None:
    modules = app_tables.cms_modules.search(
      order_by("position"), page=page, enabled=True
    )[:100]
    chunks = []
    for row in modules:
      content = row["content"] or {}
      if content.get("html"):
        chunks.append(content["html"])
    if chunks:
      settings = page["settings"] or {}
      return {
        "ok": True,
        "code": code,
        "slug": slug,
        "title": page["title"],
        "html": "".join(chunks),
        "updated_at": page["updated_at"].strftime("%d.%m.%Y %H:%M UTC")
        if page["updated_at"] else "",
        "source": settings.get("price_source", ""),
      }

  meta = PRICE_META[code]
  return {
    "ok": True,
    "code": code,
    "slug": slug,
    "title": meta["title"],
    "html": PAGE_HTML[code](),
    "updated_at": "",
    "source": {
      "conditioners": SOURCE_CONDITIONING,
      "vrf": SOURCE_VRF,
      "ventilation": SOURCE_VENTILATION,
    }[code],
  }
