def _esc(value):
  return html.escape(str(value), quote=True)


def _table(headers, rows):
  head = "".join("<th>{}</th>".format(_esc(value)) for value in headers)
  body = "".join(
    "<tr>{}</tr>".format("".join("<td>{}</td>".format(_esc(value)) for value in row))
    for row in rows
  )
  return "<table class='price-page__table'><thead><tr>{}</tr></thead><tbody>{}</tbody></table>".format(
    head, body
  )


